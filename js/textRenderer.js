/**
 * textRenderer.js — Render text onto the DotaGrid
 * Uses a built-in 5×7 pixel font bitmap to place dots on the grid.
 * Supports ASCII and some Cyrillic characters.
 */

class TextRenderer {
  constructor(grid) {
    this.grid = grid;
    this._font = PIXEL_FONT;
  }

  /**
   * Render text string onto grid at grid position (startCol, startRow)
   * @param {string} text
   * @param {number} startCol
   * @param {number} startRow
   * @param {string} symbol
   * @param {number} scale  — integer pixel multiplier (1..5)
   * @param {number} spacing — columns between characters (at scale 1)
   */
  render(text, startCol, startRow, symbol = '.', scale = 1, spacing = 1) {
    const font = this._font;
    let col = startCol;

    for (const ch of text) {
      const glyph = font[ch] ?? font['?'] ?? null;
      if (!glyph) {
        col += (5 + spacing) * scale;
        continue;
      }

      // glyph is array of rows, each row is a bitmask (5 bits wide)
      const rows = glyph.length;
      for (let r = 0; r < rows; r++) {
        for (let b = 4; b >= 0; b--) {
          if (glyph[r] & (1 << b)) {
            const dc = (4 - b) * scale;
            const dr = r * scale;
            for (let sy = 0; sy < scale; sy++) {
              for (let sx = 0; sx < scale; sx++) {
                this.grid.setCell(col + dc + sx, startRow + dr + sy, symbol);
              }
            }
          }
        }
      }

      col += (5 + spacing) * scale;
    }
  }

  /**
   * Like render() but returns {col, row, symbol}[] WITHOUT modifying the grid.
   * Used for live text preview overlay.
   */
  getCells(text, startCol, startRow, symbol = '.', scale = 1, spacing = 1) {
    const font  = this._font;
    const cells = [];
    let col = startCol;

    for (const ch of text) {
      const glyph = font[ch] ?? font['?'] ?? null;
      if (!glyph) { col += (5 + spacing) * scale; continue; }

      const rows = glyph.length;
      for (let r = 0; r < rows; r++) {
        for (let b = 4; b >= 0; b--) {
          if (glyph[r] & (1 << b)) {
            const dc = (4 - b) * scale;
            const dr = r * scale;
            for (let sy = 0; sy < scale; sy++)
              for (let sx = 0; sx < scale; sx++)
                cells.push({ col: col + dc + sx, row: startRow + dr + sy, symbol });
          }
        }
      }
      col += (5 + spacing) * scale;
    }
    return cells;
  }
}

